export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Método no permitido' });
  }
  const { numero_empleado } = req.body;
  if (!numero_empleado) {
    return res.status(400).json({ error: 'Número de empleado requerido' });
  }
  try {
    const { data, error } = await supabase
      .from('colaboradores')
      .select('*')
      .eq('numero_empleado', numero_empleado)
      .single();
    if (error || !data) {
      return res.status(404).json({ error: 'Colaborador no encontrado' });
    }
    return res.status(200).json({
      nombre: data.nombre || '',
      area: data.area || '',
      email_colaborador: data.email_colaborador || '',
      email_supervisor: data.email_supervisor || ''
    });
  } catch (err) {
    return res.status(500).json({ error: 'Error interno del servidor' });
  }
}

